    parser.add_argument("--output_dir", default="outputs/dino_r50_4scale")
    parser.add_argument("--data_path", default="data/nycu-hw2-data")
    parser.add_argument("--batch_size", default=4, type=int)
    parser.add_argument("--num_workers", default=4, type=int)
    parser.add_argument("--epochs", default=24, type=int)
    parser.add_argument("--lr_drop", default=20, type=int)
    parser.add_argument("--lr", default=1e-4, type=float)
    parser.add_argument("--lr_backbone", default=1e-5, type=float)
    parser.add_argument("--weight_decay", default=1e-4, type=float)
    parser.add_argument("--clip_max_norm", default=0.1, type=float)
    parser.add_argument("--num_queries", default=900, type=int)
    parser.add_argument("--num_feature_levels", default=4, type=int)
    parser.add_argument("--hidden_dim", default=256, type=int)
    parser.add_argument("--dn_number", default=100, type=int)
    parser.add_argument("--dn_label_noise_ratio", default=0.5, type=float)
    parser.add_argument("--dn_box_noise_scale", default=0.4, type=float)
    parser.add_argument("--num_classes", default=11, type=int)
    parser.add_argument("--resume", default="")
    parser.add_argument("--start_epoch", default=0, type=int)
    parser.add_argument("--eval", action="store_true")
    parser.add_argument("--test", action="store_true")
    parser.add_argument("--checkpoint", default="")
    parser.add_argument("--amp", dest="amp", action="store_true")
    parser.add_argument("--no_amp", dest="amp", action="store_false")
    parser.set_defaults(amp=True)
    parser.add_argument("--amp_dtype", default="bf16", choices=["fp16", "bf16"])
    parser.add_argument("--debug_max_iters", default=None, type=int)
    parser.add_argument("--seed", default=42, type=int)
    parser.add_argument("--device", default="cuda")

    parser.add_argument("--backbone", default="resnet50")
    parser.add_argument("--position_embedding", default="sine")
    parser.add_argument("--dilation", action="store_true")
    parser.add_argument("--return_interm_indices", default=[1, 2, 3], nargs="+", type=int)
